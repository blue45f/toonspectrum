export type StudioAppSettingsCenterProfileCopyPart = "label" | "description" | "recommendedFor";
export type StudioAppSettingsCenterSearchCopyPart = "label" | "description";

export function studioAppSettingsCenterProfileCopyKey(
  profileId: StudioAppSettingsProfileId,
  part: StudioAppSettingsCenterProfileCopyPart,
): string {
  return `studio.settings.center.profile.${profileId}.${part}`;
}

export function studioAppSettingsCenterSearchCopyKey(
  entryId: string,
  part: StudioAppSettingsCenterSearchCopyPart,
): string {
  return `studio.settings.center.search.${entryId}.${part}`;
}

export function formatStudioAppSettingsCenterText(
  template: string,
  values: Readonly<Record<string, string | number>>,
): string {
  return template.replace(/\{([a-zA-Z0-9_]+)\}/gu, (match, key: string) => {
    const value = values[key];
    return value === undefined ? match : String(value);
  });
}

