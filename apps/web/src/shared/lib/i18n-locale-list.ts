// 선택 가능한 로케일 목록은 "지금 DICT에 로드돼 있는 것"이 아니라 제품 카탈로그를 기준으로
// 정한다. 사전이 지연 로드로 바뀐 뒤 DICT.keys()는 세션 진행에 따라 커지므로, 목록의 기준으로
// 쓰면 언어 선택기가 방문 순서에 따라 달라진다.
export const NORMALIZED_LOCALE_OPTIONS = (() => {
  const set = new Set<string>();
  for (const locale of WORLD_LANGUAGE_LOCALE_LIST) {
    const normalized = normalizeLocaleCode(locale);
    if (normalized) set.add(normalized);
  }
  return [...set];
})();
