import assert from "node:assert/strict";
import { existsSync } from "node:fs";
import { mkdir, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { chromium } from "playwright";
const base = process.env.FORTUNE_BASE_URL ?? "http://127.0.0.1:5298";
const output = process.env.FORTUNE_EVIDENCE_DIR ?? join(tmpdir(), "fortune-cinematic-evidence");
await mkdir(output, { recursive: true });
const chrome = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";
const browser = await chromium.launch({ executablePath: process.env.FORTUNE_CHROME_PATH ?? (existsSync(chrome) ? chrome : undefined), headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: "reduce", hasTouch: true });
const page = await context.newPage(); const errors = []; const checks = [];
page.on("pageerror", (error) => errors.push(String(error)));
await page.route("**/api/fortune/**", (route) => route.abort());
const overflowCheck = async (label) => { for (const width of [320, 390, 768, 1440]) { await page.setViewportSize({ width, height: 950 }); assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, `${label} overflow at ${width}`); } checks.push(`${label}: 320/390/768/1440 overflow`); };
try {
  await page.goto(`${base}/fortune`, { waitUntil: "domcontentloaded", timeout: 120000 });
  await page.locator('[data-fortune-experience="cinematic-v1"]').waitFor({ timeout: 120000 });
  await page.getByRole("heading", { name: /운세 관측소/ }).waitFor();
  await overflowCheck("landing");
  await page.screenshot({ path: join(output, "landing-desktop.png"), fullPage: true });
  await page.getByRole("button", { name: /마음을 알고 싶어요/ }).click();
  assert.equal(await page.getByRole("button", { name: /마음을 알고 싶어요/ }).getAttribute("aria-pressed"), "true");
  await page.locator(".fo-intent-recommendations").getByRole("button", { name: /협업 궁합/ }).click();
  assert.ok(page.url().includes("content=team-match")); checks.push("mood recommendation navigation");
  await page.goto(`${base}/fortune?content=tarot-three`);
  await page.getByRole("radio").first().waitFor(); assert.equal(await page.getByRole("radio").count(), 22);
  assert.equal(await page.getByRole("radio", { checked: true }).count(), 0);
  await page.getByRole("radio", { name: "5번 카드", exact: true }).check();
  await page.getByRole("button", { name: "카드 섞기", exact: true }).click();
  assert.equal(await page.getByRole("radio", { checked: true }).count(), 0);
  assert.equal(new Set(await page.getByRole("radio").evaluateAll((radios) => radios.map((radio) => radio.value))).size, 22);
  await page.getByRole("radio", { name: "5번 카드", exact: true }).check();
  await page.getByRole("button", { name: "3카드 타로 열기", exact: true }).click();
  await page.getByRole("heading", { name: "이야기의 첫 장", exact: true }).waitFor();
  assert.equal(await page.locator(".fo-story-scene").evaluate((element) => getComputedStyle(element).animationName), "none");
  await page.getByRole("button", { name: "다음 컷", exact: true }).focus(); await page.keyboard.press("ArrowRight");
  await page.locator(".fo-story-tarot").waitFor(); checks.push("keyboard reader and reduced motion");
  await page.screenshot({ path: join(output, "tarot-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: join(output, "tarot-mobile.png"), fullPage: true });
  const previous = await page.locator(".fo-story-status").textContent();
  await page.locator(".fo-story-scene").dispatchEvent("pointerdown", { pointerType: "touch", clientX: 240, clientY: 180 });
  await page.locator(".fo-story-scene").dispatchEvent("pointerup", { pointerType: "touch", clientX: 140, clientY: 183 });
  assert.notEqual(await page.locator(".fo-story-status").textContent(), previous); checks.push("touch horizontal gesture");
  await page.getByRole("button", { name: "상세 리포트", exact: true }).click();
  assert.equal(await page.locator(".fo-tarot-results figure").count(), 3); checks.push("complete 3-card report");
  await page.getByRole("button", { name: "웹툰으로 읽기", exact: true }).click();
  await overflowCheck("tarot result");
  for (const checkbox of await page.locator(".fo-mission-tasks input").all()) await checkbox.check();
  await page.getByText("3 / 3 완료", { exact: true }).waitFor(); checks.push("creative mission checklist");
  assert.equal(await page.getByRole("link", { name: "스튜디오에서 그리기", exact: true }).getAttribute("href"), "/studio");
  await page.evaluate(() => { Object.defineProperty(navigator, "clipboard", { configurable: true, value: { writeText: async () => { throw new Error("denied for test"); } } }); });
  await page.getByRole("button", { name: "해석 복사", exact: true }).click();
  await page.getByRole("textbox", { name: "직접 복사할 해석", exact: true }).waitFor(); checks.push("clipboard denied fallback");
  assert.equal(await page.evaluate(() => localStorage.getItem("toonstudio-fortune-observatory-v1")), null);
  await page.getByRole("button", { name: "해석 보관", exact: true }).click();
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem("toonstudio-fortune-observatory-v1")).notebook.length), 1);
  await page.getByRole("button", { name: /나의 보관함/ }).click();
  await page.locator("#fo-notebook").waitFor(); assert.equal(await page.locator("#fo-notebook").evaluate((element) => element === document.activeElement), true); checks.push("explicit notebook save and focus");
  await page.goto(`${base}/fortune?content=dream`); await page.getByRole("button", { name: "+ 고양이", exact: true }).click();
  assert.equal(await page.getByLabel("기억나는 꿈의 장면", { exact: false }).first().inputValue(), "고양이");
  await page.getByRole("button", { name: "꿈 상징 사전 열기", exact: true }).click();
  await page.getByRole("heading", { name: "이야기의 첫 장", exact: true }).waitFor(); await overflowCheck("dream result");
  await page.goto(`${base}/fortune?content=lucky`); await page.getByRole("button", { name: "행운 팔레트 열기", exact: true }).click();
  await page.locator(".fo-palettes button").first().waitFor(); assert.ok(await page.locator(".fo-palettes button").count() >= 3); checks.push("palette copy actions");
  await page.goto(`${base}/fortune`); await page.getByRole("heading", { name: /운세 관측소/ }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 }); await page.screenshot({ path: join(output, "landing-mobile.png"), fullPage: true });
  assert.deepEqual(errors, []); await writeFile(join(output, "result.json"), JSON.stringify({ passed: true, checks, errors }, null, 2));
  console.log(JSON.stringify({ passed: true, checks, errors }, null, 2));
} catch (error) {
  await page.screenshot({ path: join(output, "failure.png"), fullPage: true });
  await writeFile(join(output, "result.json"), JSON.stringify({ passed: false, error: String(error), checks, errors }, null, 2));
  console.error(error); process.exitCode = 1;
} finally { await browser.close(); }
