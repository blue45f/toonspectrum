import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, renameSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, extname, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const cwd = dirname(fileURLToPath(import.meta.url));
const root = resolve(cwd, "../../..");
const publicBrand = resolve(root, "apps/web/public/brand");
const defaultVideo = resolve(publicBrand, "toonstudio-product-tour.mp4");
const narration = resolve(cwd, "audio/toonstudio-product-tour-narration.ko.m4a");
const narrationMetadata = resolve(cwd, "audio/toonstudio-product-tour-narration.ko.json");
const inkAndStarlight = resolve(root, "apps/web/public/audio/original/ink-and-starlight-instrumental.mp3");
const atlasOfStarlight = resolve(root, "apps/web/public/audio/original/atlas-of-starlight-instrumental.mp3");
const manifestPath = resolve(publicBrand, "product-tour-manifest.json");
const generatedAssetPath = resolve(root, "apps/web/src/domains/marketing/product-tour-asset.generated.ts");
const duration = 504;

function argument(name, fallback) {
  const index = process.argv.indexOf(name);
  return index >= 0 && process.argv[index + 1] ? resolve(process.cwd(), process.argv[index + 1]) : fallback;
}

function run(command, args, { capture = false } = {}) {
  const result = spawnSync(command, args, {
    cwd,
    encoding: "utf8",
    stdio: capture ? "pipe" : "inherit",
    timeout: 1_800_000,
  });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`${command} exited with ${result.status}${result.stderr ? `\n${result.stderr}` : ""}`);
  return result.stdout ?? "";
}

function sha256(path) {
  return createHash("sha256").update(readFileSync(path)).digest("hex");
}

function probe(path) {
  const raw = run("ffprobe", [
    "-v", "error",
    "-show_entries", "format=duration,size:stream=codec_name,codec_type,channels,sample_rate",
    "-of", "json",
    path,
  ], { capture: true });
  return JSON.parse(raw);
}

function verifyMixedVideo(path) {
  const media = probe(path);
  const mediaDuration = Number(media.format?.duration);
  const video = media.streams?.filter((stream) => stream.codec_type === "video") ?? [];
  const audio = media.streams?.filter((stream) => stream.codec_type === "audio") ?? [];
  if (Math.abs(mediaDuration - duration) > 0.1) throw new Error(`Unexpected product tour duration: ${mediaDuration}`);
  if (video.length !== 1 || video[0].codec_name !== "h264") throw new Error("Product tour must contain one H.264 video stream");
  if (audio.length !== 1 || audio[0].codec_name !== "aac" || Number(audio[0].channels) !== 2) throw new Error("Product tour must contain one stereo AAC stream");
  const bytes = statSync(path).size;
  if (bytes < 5_000_000 || bytes > 28 * 1024 * 1024) throw new Error(`Unexpected product tour size: ${bytes}`);
  const header = readFileSync(path).subarray(0, Math.min(bytes, 2 * 1024 * 1024));
  const moov = header.indexOf(Buffer.from("moov"));
  const mdat = header.indexOf(Buffer.from("mdat"));
  if (moov < 0 || mdat < 0 || moov > mdat) throw new Error("Product tour is not fast-start optimized");
  return { bytes, sha256: sha256(path), media };
}

function assetModule({ bytes, sha256: digest }) {
  const revision = digest.slice(0, 16);
  return `// Generated by tools/media/brand-film/mix-product-tour-audio.mjs.\nexport const PRODUCT_TOUR_ASSET = {\n  src: "/brand/toonstudio-product-tour.mp4?v=${revision}",\n  bytes: ${bytes},\n  sha256: "${digest}",\n  revision: "${revision}",\n  narrationLocale: "ko-KR",\n  hasOriginalBgm: true,\n} as const;\n`;
}

function buildManifest(verified) {
  const narrationInfo = JSON.parse(readFileSync(narrationMetadata, "utf8"));
  const sourceCommit = process.env.GITHUB_SHA || "local";
  return {
    version: 2,
    composition: "ToonStudioProductTour",
    duration,
    fps: 30,
    src: "/brand/toonstudio-product-tour.mp4",
    poster: "/brand/toonstudio-product-tour-poster.jpg",
    captions: { ko: "/brand/toonstudio-product-tour.ko.vtt", en: "/brand/toonstudio-product-tour.en.vtt" },
    audio: {
      narration: { locale: "ko-KR", voice: narrationInfo.voice, disclosure: narrationInfo.disclosure, sha256: narrationInfo.audioSha256 },
      bgm: [
        { id: "ink-and-starlight-instrumental", sha256: sha256(inkAndStarlight) },
        { id: "atlas-of-starlight-instrumental", sha256: sha256(atlasOfStarlight) },
      ],
      mix: "stereo-aac-128k-with-narration-ducking",
    },
    bytes: verified.bytes,
    sha256: verified.sha256,
    sourceCommit,
  };
}

function writeReleaseMetadata(verified) {
  const manifest = buildManifest(verified);
  mkdirSync(dirname(manifestPath), { recursive: true });
  writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
  writeFileSync(generatedAssetPath, assetModule(verified));
  return manifest;
}

function verifyReleaseMetadata(verified) {
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  if (manifest.version !== 2 || manifest.bytes !== verified.bytes || manifest.sha256 !== verified.sha256) throw new Error("Product tour manifest is stale");
  if (readFileSync(generatedAssetPath, "utf8") !== assetModule(verified)) throw new Error("Product tour asset module is stale");
  const narrationInfo = JSON.parse(readFileSync(narrationMetadata, "utf8"));
  if (manifest.audio?.narration?.sha256 !== narrationInfo.audioSha256) throw new Error("Product tour narration manifest is stale");
  return manifest;
}

const input = argument("--input", defaultVideo);
const output = argument("--output", defaultVideo);
const checkOnly = process.argv.includes("--check");

if (checkOnly) {
  const verified = verifyMixedVideo(output);
  const manifest = verifyReleaseMetadata(verified);
  console.log(JSON.stringify({ ok: true, bytes: verified.bytes, sha256: verified.sha256, audio: manifest.audio }, null, 2));
  process.exit(0);
}

const extension = extname(output) || ".mp4";
const temporaryOutput = resolve(dirname(output), `.${Date.now()}-${process.pid}-toonstudio-product-tour${extension}`);
const filter = [
  "[2:a]atrim=start=0:end=240,asetpts=PTS-STARTPTS,volume=-16dB[score_a]",
  "[3:a]atrim=start=0:end=180,asetpts=PTS-STARTPTS,volume=-16dB[score_b]",
  "[2:a]atrim=start=120:end=210,asetpts=PTS-STARTPTS,volume=-16dB[score_c]",
  "[score_a][score_b]acrossfade=d=3:c1=tri:c2=tri[score_ab]",
  "[score_ab][score_c]acrossfade=d=3:c1=tri:c2=tri,afade=t=in:st=0:d=2,afade=t=out:st=500:d=4[score]",
  "[1:a]aresample=48000,pan=stereo|c0=c0|c1=c0,volume=-2dB,asplit=2[voice_side][voice_mix]",
  "[score][voice_side]sidechaincompress=threshold=0.015:ratio=10:attack=18:release=550:knee=3[ducked]",
  "[ducked][voice_mix]amix=inputs=2:duration=longest:normalize=0,alimiter=limit=0.891:attack=5:release=80:level=false,atrim=duration=504[mixed]",
].join(";");

try {
  run("ffmpeg", [
    "-y",
    "-i", input,
    "-i", narration,
    "-i", inkAndStarlight,
    "-i", atlasOfStarlight,
    "-filter_complex", filter,
    "-map", "0:v:0",
    "-map", "[mixed]",
    "-map_metadata", "0",
    "-c:v", "copy",
    "-c:a", "aac",
    "-b:a", "128k",
    "-ar", "48000",
    "-ac", "2",
    "-metadata:s:a:0", "language=kor",
    "-metadata:s:a:0", "title=Korean narration and ToonStudio original OST",
    "-metadata", "comment=ToonStudio product tour with synthesized Korean narration and original ACE-Step soundtrack",
    "-movflags", "+faststart",
    "-t", String(duration),
    temporaryOutput,
  ]);
  const verified = verifyMixedVideo(temporaryOutput);
  mkdirSync(dirname(output), { recursive: true });
  renameSync(temporaryOutput, output);
  const manifest = writeReleaseMetadata(verified);
  console.log(JSON.stringify({ output, ...verified, audio: manifest.audio }, null, 2));
} catch (error) {
  rmSync(temporaryOutput, { force: true });
  throw error;
}
