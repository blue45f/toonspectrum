import { createHash } from "node:crypto";
import {
  copyFileSync,
  mkdirSync,
  readFileSync,
  renameSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const cwd = dirname(fileURLToPath(import.meta.url));
const root = resolve(cwd, "../../..");
const publicDirectory = resolve(root, "apps/web/public/brand/product-tour");
const sourceNarration = resolve(cwd, "audio/toonstudio-product-tour-narration.ko.m4a");
const sourceMetadata = resolve(cwd, "audio/toonstudio-product-tour-narration.ko.json");
const ink = resolve(root, "apps/web/public/audio/original/ink-and-starlight-instrumental.mp3");
const atlas = resolve(root, "apps/web/public/audio/original/atlas-of-starlight-instrumental.mp3");
const publicNarration = resolve(publicDirectory, "toonstudio-product-tour-narration.ko.m4a");
const publicBgm = resolve(publicDirectory, "toonstudio-product-tour-bgm.m4a");
const publicManifest = resolve(publicDirectory, "product-tour-audio.json");
const generatedModule = resolve(root, "apps/web/src/domains/marketing/product-tour-audio.generated.ts");
const duration = 504;
const checkOnly = process.argv.includes("--check");

function run(command, args, { capture = false } = {}) {
  const result = spawnSync(command, args, {
    cwd,
    encoding: "utf8",
    stdio: capture ? "pipe" : "inherit",
    timeout: 1_800_000,
  });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(`${command} exited with ${result.status}${result.stderr ? `\n${result.stderr}` : ""}`);
  }
  return result.stdout ?? "";
}

function sha256(path) {
  return createHash("sha256").update(readFileSync(path)).digest("hex");
}

function probe(path) {
  const raw = run("ffprobe", [
    "-v", "error",
    "-show_entries", "format=duration,size:stream=codec_name,codec_type,channels,sample_rate",
    "-of", "json",
    path,
  ], { capture: true });
  return JSON.parse(raw);
}

function verifyAudio(path, expectedChannels) {
  const media = probe(path);
  const mediaDuration = Number(media.format?.duration);
  const streams = media.streams?.filter((stream) => stream.codec_type === "audio") ?? [];
  if (Math.abs(mediaDuration - duration) > 0.1) {
    throw new Error(`Unexpected audio duration for ${path}: ${mediaDuration}`);
  }
  if (streams.length !== 1 || streams[0].codec_name !== "aac") {
    throw new Error(`Expected one AAC stream in ${path}`);
  }
  if (Number(streams[0].channels) !== expectedChannels) {
    throw new Error(`Unexpected channel count in ${path}: ${streams[0].channels}`);
  }
  if (Number(streams[0].sample_rate) !== 48_000) {
    throw new Error(`Unexpected sample rate in ${path}: ${streams[0].sample_rate}`);
  }
  return {
    bytes: statSync(path).size,
    duration: mediaDuration,
    sha256: sha256(path),
  };
}

function runtimeManifest(narration, bgm, metadata) {
  const cues = metadata.cues.map(({ start, duration: cueDuration, ko, en }) => ({
    start,
    duration: cueDuration,
    ko,
    en,
  }));
  const combined = createHash("sha256")
    .update(narration.sha256)
    .update(bgm.sha256)
    .digest("hex");
  return {
    version: 1,
    duration,
    fps: 30,
    revision: combined.slice(0, 16),
    narration: {
      src: `/brand/product-tour/toonstudio-product-tour-narration.ko.m4a?v=${combined.slice(0, 16)}`,
      locale: metadata.locale,
      voice: metadata.voice,
      disclosure: metadata.disclosure,
      ...narration,
    },
    bgm: {
      src: `/brand/product-tour/toonstudio-product-tour-bgm.m4a?v=${combined.slice(0, 16)}`,
      title: "Ink and Starlight × Atlas of Starlight",
      mix: "crossfaded-original-score-with-runtime-ducking",
      ...bgm,
    },
    cues,
  };
}

function moduleSource(manifest) {
  return `// Generated by tools/media/brand-film/generate-product-tour-runtime-audio.mjs.\n`
    + `export const PRODUCT_TOUR_RUNTIME_AUDIO = ${JSON.stringify(manifest, null, 2)} as const;\n`;
}

function buildBgm() {
  const temporary = resolve(publicDirectory, `.product-tour-bgm-${process.pid}.m4a`);
  const filter = [
    "[0:a]atrim=start=0:end=240,asetpts=PTS-STARTPTS[score_a]",
    "[1:a]atrim=start=0:end=180,asetpts=PTS-STARTPTS[score_b]",
    "[0:a]atrim=start=120:end=210,asetpts=PTS-STARTPTS[score_c]",
    "[score_a][score_b]acrossfade=d=3:c1=tri:c2=tri[score_ab]",
    "[score_ab][score_c]acrossfade=d=3:c1=tri:c2=tri,afade=t=in:st=0:d=2,afade=t=out:st=500:d=4,loudnorm=I=-18:TP=-1.5:LRA=8,apad=whole_dur=504,atrim=duration=504[out]",
  ].join(";");
  try {
    run("ffmpeg", [
      "-y",
      "-i", ink,
      "-i", atlas,
      "-filter_complex", filter,
      "-map", "[out]",
      "-c:a", "aac",
      "-b:a", "96k",
      "-ar", "48000",
      "-ac", "2",
      "-movflags", "+faststart",
      temporary,
    ]);
    renameSync(temporary, publicBgm);
  } catch (error) {
    rmSync(temporary, { force: true });
    throw error;
  }
}

const metadata = JSON.parse(readFileSync(sourceMetadata, "utf8"));
if (metadata.audioSha256 !== sha256(sourceNarration)) {
  throw new Error("The reviewed narration file does not match its metadata");
}

if (!checkOnly) {
  mkdirSync(publicDirectory, { recursive: true });
  copyFileSync(sourceNarration, publicNarration);
  buildBgm();
}

const narration = verifyAudio(publicNarration, 1);
const bgm = verifyAudio(publicBgm, 2);
const manifest = runtimeManifest(narration, bgm, metadata);
const expectedModule = moduleSource(manifest);

if (checkOnly) {
  const storedManifest = JSON.parse(readFileSync(publicManifest, "utf8"));
  if (JSON.stringify(storedManifest) !== JSON.stringify(manifest)) {
    throw new Error("Product tour runtime audio manifest is stale");
  }
  if (readFileSync(generatedModule, "utf8") !== expectedModule) {
    throw new Error("Product tour runtime audio module is stale");
  }
} else {
  writeFileSync(publicManifest, `${JSON.stringify(manifest, null, 2)}\n`);
  writeFileSync(generatedModule, expectedModule);
}

console.log(JSON.stringify({
  ok: true,
  revision: manifest.revision,
  narration: { bytes: narration.bytes, sha256: narration.sha256 },
  bgm: { bytes: bgm.bytes, sha256: bgm.sha256 },
  cues: manifest.cues.length,
}, null, 2));
