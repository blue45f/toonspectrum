import assert from 'node:assert/strict';
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const ts=createRequire(import.meta.url)('typescript');
const filename='apps/web/src/domains/creator/spatial-reader/spatial-caption-pages.ts';
const compiled=ts.transpileModule(readFileSync(join(root,filename),'utf8'),{fileName:filename,reportDiagnostics:true,compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}});
assert.equal(compiled.diagnostics?.filter(item=>item.category===ts.DiagnosticCategory.Error).length,0);
const {spatialCaptionPages}=await import(`data:text/javascript;base64,${Buffer.from(compiled.outputText).toString('base64')}`);
const input='가나다라😀'.repeat(100),pages=spatialCaptionPages(input);
assert.equal(pages.join('').replace(/\n/gu,''),input);
assert.ok(pages.every(page=>page.split('\n').length<=4&&page.split('\n').every(line=>Array.from(line).length<=28)));
const lines=Array.from({length:30},(_,i)=>`대사 ${i}`).join('\n');
assert.equal(spatialCaptionPages(lines).join('\n'),lines);
assert.equal(spatialCaptionPages(lines).length,8);
assert.equal(spatialCaptionPages('').length,1);
const report={passed:4,failed:0,scope:'One transpile syntax check and three pure-function cases. No rendered label or headset test.',tests:['TypeScript syntax','long Unicode caption content/line/page limits','explicit newline pagination without clipping','empty caption']};
mkdirSync(join(root,'artifacts/local-first'),{recursive:true});writeFileSync(join(root,'artifacts/local-first/spatial-captions.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));
