#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const inputPath = resolve(root, "config/free-database-federation.json");
const outputPath = resolve(
  root,
  "apps/api/src/platform/federated-data-plane/federated-data-plane-policy.generated.ts",
);
const check = process.argv.slice(2).includes("--check");

const policy = JSON.parse(readFileSync(inputPath, "utf8"));
const runtime = {
  version: policy.version,
  quotaSnapshotMaxAgeSeconds: policy.quotaSnapshotMaxAgeSeconds,
  providers: Object.fromEntries(
    Object.entries(policy.providers).map(([providerId, provider]) => [
      providerId,
      {
        billingBoundary: provider.billingBoundary,
        applicationHardCapRatio: provider.applicationHardCapRatio,
        trafficWeight: provider.trafficWeight,
      },
    ]),
  ),
  shards: Object.fromEntries(
    Object.entries(policy.shards).map(([shardId, shard]) => [
      shardId,
      {
        provider: shard.provider,
        domains: shard.domains,
        virtualShardCount: shard.virtualShardCount,
        writeMode: shard.writeMode,
      },
    ]),
  ),
  routes: policy.routes,
};

const source = `// Generated by scripts/generate-federated-data-plane-policy.mjs.
// Edit config/free-database-federation.json, then regenerate this file.
import type { FederatedDataPlanePolicyDefinition } from "./federated-data-plane.contract";

export const FEDERATED_DATA_PLANE_POLICY = ${JSON.stringify(runtime, null, 2)} as const satisfies FederatedDataPlanePolicyDefinition;
`;

if (check) {
  const current = readFileSync(outputPath, "utf8");
  if (current !== source) {
    throw new Error(
      "Generated federated data-plane policy is stale. Run pnpm run generate:federated-data-plane-policy",
    );
  }
  process.stdout.write("Federated data-plane generated policy: current\n");
} else {
  writeFileSync(outputPath, source);
  process.stdout.write(`Generated ${outputPath}\n`);
}
