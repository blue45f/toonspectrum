#!/usr/bin/env node
/** Native component/browser integration; not a full Studio save/restore assertion. */
import assert from 'node:assert/strict';
import {mkdir,readFile,writeFile,rm} from 'node:fs/promises';
import path from 'node:path';
import {createServer} from 'vite';
import {chromium} from 'playwright';

const root=process.cwd();
const output=path.resolve(process.argv[2] ?? 'test-results/studio-asset-curation');
const fixture=path.join(root,'__asset_curation_fixture__');
const checks=[];
let server,browser,page;
await mkdir(output,{recursive:true});
await mkdir(fixture,{recursive:false});
try {
  const manifest=JSON.parse(await readFile(path.join(root,'public/assets/studio/cc0-20260906/manifest.json'),'utf8'));
  const detailed=manifest.assets.filter(a=>a.kind==='model'&&a.license.provider==='Poly Haven');
  assert.equal(detailed.length,17);
  const standalone=detailed.filter(a=>!a.id.startsWith('polyhaven-modular-street-seating')).length;
  await writeFile(path.join(fixture,'index.html'),'<!doctype html><html lang="ko"><meta charset="utf-8"><meta name="viewport" content="width=device-width"><title>Studio asset component verification</title><div id="root"></div><script type="module" src="/__asset_curation_fixture__/entry.tsx"></script></html>');
  await writeFile(path.join(fixture,'entry.tsx'),`
import {useState} from 'react';
import {createRoot} from 'react-dom/client';
import {StudioCc0AssetLibraryPanel} from '/src/domains/creator/StudioCc0AssetLibraryPanel.tsx';
import '/src/styles/globals.css';
function App(){const [inserted,setInserted]=useState(null);return <main className="mx-auto min-h-screen w-full max-w-xl bg-canvas p-3 text-fg"><h1 className="mb-3 text-lg font-bold">에셋 라이브러리 검증</h1><StudioCc0AssetLibraryPanel onUseAsset={asset=>{setInserted({id:asset.id,width:asset.width,height:asset.height,license:asset.rights?.licenseId,bytes:asset.dataUrl.length});return true;}}/><output data-inserted-id={inserted?.id ?? ''}>{inserted ? JSON.stringify(inserted) : ''}</output></main>}
createRoot(document.getElementById('root')).render(<App/>);`);
  server=await createServer({root,server:{host:'127.0.0.1',port:0},logLevel:'warn'});
  await server.listen();
  const address=server.httpServer.address();
  assert(address&&typeof address==='object');
  const base=`http://127.0.0.1:${address.port}`;
  browser=await chromium.launch({headless:true,args:['--disable-dev-shm-usage']});
  const context=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:1,acceptDownloads:true});
  const errors=[];
  page=await context.newPage();
  page.on('pageerror',error=>errors.push(error.message));
  let manifestRequests=0;
  page.on('request',request=>{if(request.url().endsWith('/cc0-20260906/manifest.json'))manifestRequests++;});
  await page.goto(base+'/__asset_curation_fixture__/index.html');
  const library=page.locator('[data-studio-cc0-library="true"]');
  await library.waitFor();
  await page.waitForTimeout(150);
  assert.equal(manifestRequests,0,'Closed library must not fetch the manifest');
  checks.push('closed-library-zero-catalog-download');
  await library.locator('summary').click();
  await page.locator('[data-studio-cc0-asset]').first().waitFor();
  assert.equal(await page.locator('[data-studio-cc0-asset]').count(),24);
  assert((await page.locator('[data-studio-cc0-asset]').first().getAttribute('data-studio-cc0-asset')).startsWith('polyhaven-'));
  checks.push('real-manifest-loaded-24-tiles-detailed-source-first');
  const search=page.getByRole('searchbox',{name:'에셋 검색'});
  const style=page.getByLabel('표현 방식',{exact:true});
  const assembly=page.getByLabel('조립 부품 포함',{exact:true});
  await style.selectOption('detailed-pbr');
  await page.waitForFunction(count=>document.querySelectorAll('[data-studio-cc0-asset]').length===count,standalone);
  assert.equal(await page.locator('[data-studio-cc0-asset]').count(),standalone);
  await assembly.check();
  await page.waitForFunction(count=>document.querySelectorAll('[data-studio-cc0-asset]').length===count,detailed.length);
  checks.push('detailed-style-and-assembly-opt-in');
  await style.selectOption('all');
  await search.fill('glass wine');
  await page.getByText('현재 검색어·종류·표현 방식에 맞는 결과가 없습니다.').waitFor();
  assert.equal(await page.locator('[data-studio-cc0-asset]').count(),0);
  checks.push('quarantined-wine-unavailable-even-with-assembly');
  await search.fill('wall');
  await page.locator('[data-studio-cc0-asset]').first().waitFor();
  await assembly.uncheck();
  await page.waitForTimeout(100);
  assert.equal(await page.locator('[data-studio-cc0-asset^="kenney-building-"]').count(),0);
  checks.push('construction-components-separated-from-default-selection');
  await search.fill('');
  await page.getByRole('button',{name:'효과 마스크',exact:true}).click();
  await page.locator('[data-studio-cc0-asset^="kenney-particles-"]').first().waitFor();
  const background=await page.locator('[data-studio-cc0-asset] img').first().evaluate(image=>getComputedStyle(image.parentElement).backgroundColor);
  assert.equal(background,'rgb(52, 57, 67)');
  await page.screenshot({path:path.join(output,'masks-mobile.png'),fullPage:true});
  checks.push('actual-white-alpha-masks-on-dark-background');
  await page.getByRole('button',{name:'표면 재질',exact:true}).click();
  await page.locator('[data-studio-cc0-asset^="polyhaven-"]').first().waitFor();
  const firstId=await page.locator('[data-studio-cc0-asset]').first().getAttribute('data-studio-cc0-asset');
  await page.locator('[data-studio-cc0-asset]').first().getByRole('button',{name:/캔버스에 삽입$/}).click();
  await page.locator(`output[data-inserted-id="cc0:${firstId}"]`).waitFor({timeout:30000});
  const inserted=JSON.parse(await page.locator('output').textContent());
  assert.equal(inserted.license,'CC0-1.0');
  assert(inserted.width>=1024&&inserted.height>=1024&&inserted.bytes>100);
  checks.push('real-2K-image-fetch-SHA256-decode-dimensions-and-insert-callback');
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>document.documentElement.clientWidth+1);
  assert.equal(overflow,false,'390px library must not horizontally overflow');
  checks.push('390px-layout-no-horizontal-overflow');
  await page.getByRole('button',{name:'전체',exact:true}).click();
  await style.selectOption('detailed-pbr');
  await page.setViewportSize({width:920,height:980});
  await page.locator('[data-studio-cc0-asset] img').first().waitFor();
  await page.screenshot({path:path.join(output,'detailed-library-desktop.png'),fullPage:true});
  const downloadPromise=page.waitForEvent('download');
  await page.locator('[data-studio-cc0-asset]').first().getByRole('link',{name:/GLB 받기$/}).click();
  const download=await downloadPromise;
  assert(download.suggestedFilename().endsWith('.glb'));
  assert.equal(await download.failure(),null);
  checks.push('actual-GLB-download');
  const retryPage=await context.newPage();
  let failOnce=true;
  await retryPage.route('**/cc0-20260906/manifest.json',async route=>{if(failOnce){failOnce=false;await route.fulfill({status:503,body:'temporarily unavailable'});}else await route.continue();});
  await retryPage.goto(base+'/__asset_curation_fixture__/index.html');
  await retryPage.locator('[data-studio-cc0-library] summary').click();
  await retryPage.getByRole('button',{name:'다시 불러오기',exact:true}).click();
  await retryPage.locator('[data-studio-cc0-asset]').first().waitFor();
  await retryPage.close();
  checks.push('failed-manifest-retry-recovers');
  assert.deepEqual(errors,[]);
  await writeFile(path.join(output,'browser-verification.json'),JSON.stringify({passed:checks.length,checks,pageErrors:errors,mode:'actual-component-vite-browser-fixture',fullStudioSaveRestore:false},null,2)+'\n');
  console.log('ASSET BROWSER CHECKS',checks.length,JSON.stringify(checks));
} catch(error){
  await page?.screenshot({path:path.join(output,'failure.png'),fullPage:true}).catch(()=>{});
  await writeFile(path.join(output,'browser-verification.json'),JSON.stringify({passedBeforeFailure:checks,failed:String(error),fullStudioSaveRestore:false},null,2)+'\n');
  throw error;
} finally {
  await browser?.close();
  await server?.close();
  await rm(fixture,{recursive:true,force:true});
}
